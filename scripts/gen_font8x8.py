#!/usr/bin/env python3
"""Generate g3x_font8x8.h — an 8x8 1-bit ASCII glyph table for the glide3xvk
version-tag overlay, rendered from DejaVu Sans Mono (supersampled 4x, box-
filtered down, thresholded). Emits rows LSB=leftmost pixel (bit col = pixel x).

Output: glide3xvk/src/g3x_font8x8.h + a preview PNG (scripts/font8x8_preview.png)
"""
from PIL import Image, ImageFont, ImageDraw

import os
FONT = os.environ.get("DEJAVU_MONO_BOLD",
                    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf")
SS = 4                     # supersample factor
TILE = 8 * SS              # 32x32 work tile per glyph
FIRST, COUNT = 0x20, 0x5F  # 0x20..0x7E
THRESH = 100               # 0..255 coverage threshold after box filter

font = ImageFont.truetype(FONT, 11 * SS)   # ~11px em at 1x -> cap ~8px... tuned below
# DejaVu Sans Mono Bold: cap height ~0.73em. For 7px caps at 1x: em ~ 9.6px.
# 11px em gives slightly wide glyphs; use 10px em (size 10*SS=40).
font = ImageFont.truetype(FONT, 10 * SS)
BASE = 7 * SS + SS // 2    # baseline y in tile (30): caps top at ~1..2, descenders fit

def render_char(ch):
    """Return 8 bytes (rows, bit0=leftmost) for ch, or None if blank."""
    if ch == " ":
        return [0] * 8
    tile = Image.new("L", (TILE, TILE), 0)
    d = ImageDraw.Draw(tile)
    # pen at x=0; mono advance at 10px em = 6.02px*4 = 24 < 32 OK
    d.text((0, BASE), ch, font=font, fill=255, anchor="ls")
    bbox = tile.getbbox()
    if bbox is None:
        return [0] * 8
    # rescue tall glyphs (parens/brackets/|): shift vertically to fit
    top, bot = bbox[1], bbox[3]
    dy = 0
    if top < 0:
        dy = -top
    elif bot > TILE:
        dy = TILE - bot
    if dy:
        shifted = Image.new("L", (TILE, TILE), 0)
        shifted.paste(tile, (0, dy))
        tile = shifted
    small = tile.resize((8, 8), Image.BOX)
    px = small.load()
    rows = []
    for y in range(8):
        b = 0
        for x in range(8):
            if px[x, y] >= THRESH:
                b |= 1 << x
        rows.append(b)
    return rows

glyphs = {}
for c in range(FIRST, FIRST + COUNT):
    glyphs[c] = render_char(chr(c))

# ---- hand-tuned descender overrides ----------------------------------------
# DejaVu's descent (~2 rows at 1x) does not fit under BASE=30/32: the box
# filter crushes every tail into one broken row (field 0.4.1: "can't see the
# bottom of the g in glide"). Classic 8x8-font answer: bowls at rows 2-5
# (one middle row dropped from the generated bowl), tails get real rows 6-7.
# Rows are bytes, bit x = pixel column x (bit 0 = leftmost).
OVERRIDE = {
    # bowl rows 2-5, stem col4 row6, hook cols2-4 row7
    ord("g"): [0x00, 0x00, 0x1E, 0x13, 0x13, 0x1E, 0x10, 0x1C],
    # bowl rows 2-5, bold stem cols1-2 rows 6-7
    ord("p"): [0x00, 0x00, 0x1E, 0x36, 0x32, 0x1E, 0x06, 0x06],
    # mirror of p: bowl rows 2-5, stem col4 rows 6-7
    ord("q"): [0x00, 0x00, 0x1E, 0x1B, 0x13, 0x1E, 0x10, 0x10],
    # dot row0, stem col3 rows 2-6, hook cols1-3 row7
    ord("j"): [0x08, 0x00, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E],
    # 0.4.5: DejaVu's triple-stem 'm' collapses to a solid block at 8px (the
    # box filter fills cols 2-7 rows 2-5). Hand-drawn in the style of the
    # generated 'n' (1px stems 3 columns apart, 1px top bar, x-height body
    # rows 2-7): arch tops merged into one bar, stems at cols 1/4/7. First
    # overlay text to expose it: the Shift+V conf panel's controller keys
    # (aimsens/moveclick/home) and preset names with an 'm'.
    ord("m"): [0x00, 0x00, 0xFE, 0x92, 0x92, 0x92, 0x92, 0x92],
}
for c, rows in OVERRIDE.items():
    glyphs[c] = list(rows)

# ---- preview: render the exact overlay line as ASCII art + PNG ------------
line = "glide3xvk 0.4.2 (181780c) res-independent-scanlines.slangp"
print("preview:", line)
for y in range(8):
    row = ""
    for ch in line:
        g = glyphs[ord(ch)]
        for x in range(8):
            row += "#" if (g[y] >> x) & 1 else "."
    print(row)

# PNG preview (scaled 4x) for eyeballing
W = len(line) * 8
img = Image.new("L", (W, 8), 0)
ip = img.load()
for i, ch in enumerate(line):
    g = glyphs[ord(ch)]
    for y in range(8):
        for x in range(8):
            if (g[y] >> x) & 1:
                ip[i * 8 + x, y] = 255
img.resize((W * 4, 32), Image.NEAREST).save(os.path.join(os.path.dirname(os.path.abspath(__file__)), "font8x8_preview.png"))

# ---- emit header -----------------------------------------------------------
out = []
out.append("// g3x_font8x8.h - generated by scripts/gen_font8x8.py (DejaVu Sans Mono Bold")
out.append("// supersampled 4x -> box-filtered 8x8 -> threshold %d). DO NOT EDIT BY HAND;" % THRESH)
out.append("// re-run the generator instead. Rows are bytes, bit x = pixel column x")
out.append("// (bit 0 = leftmost), 8 rows top->bottom, ASCII 0x20..0x7E.")
out.append("// Descenders (g p q j) and the 'm' are hand-tuned overrides in the generator:")
out.append("// DejaVu's descent does not fit the tile (crushed tails) and the triple-stem")
out.append("// 'm' collapses to a solid block under the box filter.")
out.append("#pragma once")
out.append("")
out.append("#include <cstdint>")
out.append("")
out.append("#define G3X_FONT8X8_FIRST 0x%02x" % FIRST)
out.append("#define G3X_FONT8X8_COUNT %u" % COUNT)
out.append("")
out.append("static const uint8_t g3x_font8x8[G3X_FONT8X8_COUNT][8] = {")
for c in range(FIRST, FIRST + COUNT):
    g = glyphs[c]
    ch = chr(c)
    esc = "\\'" if ch == "'" else ("\\\\" if ch == "\\" else ch)
    body = ", ".join("0x%02x" % b for b in g)
    out.append("    {%s}, // U+%04X '%s'" % (body, c, esc))
out.append("};")
out.append("")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir,
                    "glide3xvk", "src", "g3x_font8x8.h")
path = os.path.normpath(path)
with open(path, "w") as f:
    f.write("\n".join(out))
print("wrote", path)
